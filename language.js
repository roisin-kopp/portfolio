export function translate(text) {
  return language === 'en' ? (english[text] ?? text) : text;
}

export function setLanguage(next) {
  language = next;
  document.documentElement.lang = next;
  for (const element of document.querySelectorAll('[data-de][data-en]')) {
    element.textContent = element.dataset[next];
  }
  for (const element of document.querySelectorAll('[data-de-label][data-en-label]')) {
    element.setAttribute('aria-label', element.dataset[`${next}Label`]);
  }
}

export function getLanguage() {
  return language;
}
